"""Lock batch job list (2026-10-22; card runs/锁定批_20261022/锁定批_卡_2026-10-22.md). Writes the queue file and
lock_runs.json, the single map from (dataset, variant, mode, split, seed) to run ids that the judge reads, so that no run
id is typed by hand twice. Code frozen at run_v1.py a41f469b (the C15 runs R20261021-102..104 used the same file).
Usage (repo root): python <this> <jobs_out> <runs_json_out>"""
import json, sys
SEEDS = [123, 42, 3047, 7, 2026]
P = "R20261022-"
BASE = {"iemocap": "--dataset iemocap --epochs 3 --cosine --seed {s} --fast_eval --eval_last --ctx 16",
        "meld": "--dataset meld --epochs 3 --cosine --focal_gamma 0.5 --seed {s} --fast_eval --eval_last --ctx 16"}
FUT = {"dual": "--future_mode dual --future_k 2 --future_pdrop 0.5", "online": "--future_mode online --future_k 2",
       "full": "--future_mode full --future_k 2"}
MODES = {"dual": ("online", "full"), "online": ("online",), "full": ("full",)}
DUMP = "_remote/smoke_textdump_future_split_20261022.py"
# reused: C15 IEMOCAP dual seeds 123 / 42 / 3047 (same args, same run_v1.py) and their dumps
REUSED_TRAIN = {123: "R20261021-102", 42: "R20261021-103", 3047: "R20261021-104"}
REUSED_DUMP = {("online", "test"): ["R20261021-111", "R20261021-112", "R20261021-113"],
               ("full", "test"): ["R20261021-114", "R20261021-115", "R20261021-116"],
               ("online", "dev"): ["R20261022-01", "R20261022-02", "R20261022-03"],
               ("full", "dev"): ["R20261022-04", "R20261022-05", "R20261022-06"]}
TRAIN_IDS = {("iemocap", "dual"): {7: 101, 2026: 102}, ("iemocap", "online"): dict(zip(SEEDS, range(103, 108))),
             ("iemocap", "full"): dict(zip(SEEDS, range(108, 113))), ("meld", "dual"): dict(zip(SEEDS, range(121, 126))),
             ("meld", "online"): dict(zip(SEEDS, range(126, 131))), ("meld", "full"): dict(zip(SEEDS, range(131, 136)))}
EXPERTS = {"iemocap": {"e1": [f"R20261021-{i}" for i in range(31, 36)], "e2": [f"R20261021-{i}" for i in range(21, 26)],
                       "e3": [f"R20261022-{i}" for i in range(11, 16)]},
           "meld": {"e1": [f"R20261021-{i}" for i in range(41, 46)], "e2": [f"R20261022-{i}" for i in range(21, 26)],
                    "e3": [f"R20261022-{i}" for i in range(26, 31)]}}
GROUPS = [[("meld", "dual"), ("iemocap", "dual")], [("meld", "online"), ("iemocap", "online"), ("meld", "full"), ("iemocap", "full")]]  # longer MELD runs first
J1, J2 = P + "210", P + "211"

runs = {ds: {"train": {}, "text": {}, "experts": EXPERTS[ds]} for ds in ("iemocap", "meld")}
train_lines, dump_lines = [[], []], [[], []]
nxt = 141
for g, group in enumerate(GROUPS):
    for ds, var in group:
        tr = {}
        for s in SEEDS:
            if ds == "iemocap" and var == "dual" and s in REUSED_TRAIN:
                tr[s] = REUSED_TRAIN[s]; continue
            rid = P + str(TRAIN_IDS[(ds, var)][s]); tr[s] = rid
            tag = f"lock_{ds}_{var}_c16_s{s}"
            train_lines[g].append(f"{rid}|run_v1.py|{BASE[ds].format(s=s)} {FUT[var]} --tag {tag}|lock train {ds} {var} s{s}|")
        runs[ds]["train"][var] = [tr[s] for s in SEEDS]
        runs[ds]["text"][var] = {}
        for m in MODES[var]:
            runs[ds]["text"][var][m] = {}
            for sp in ("dev", "test"):
                ids = []
                for i, s in enumerate(SEEDS):
                    if ds == "iemocap" and var == "dual" and s in REUSED_TRAIN:
                        ids.append(REUSED_DUMP[(m, sp)][i]); continue
                    rid = P + str(nxt); nxt += 1; ids.append(rid)
                    dump_lines[g].append(f"{rid}|{DUMP}|--src {tr[s]} --mode {m} --split {sp} --out_dir outputs/runs/{rid}/eval|lock dump {ds} {var} {m} {sp} s{s}|{tr[s]}")
                runs[ds]["text"][var][m][sp] = ids
assert nxt <= 210, nxt
deps1 = [l.split("|")[0] for l in dump_lines[0]]
deps2 = [l.split("|")[0] for l in dump_lines[1]]
head = ("# Lock batch (2026-10-22, user approved D-R and the lock card): card runs/锁定批_20261022/锁定批_卡_2026-10-22.md;"
        " generated by lock_jobs_gen_20261022.py; run_v1.py a41f469b; dumps " + DUMP + " 5a8017c0; judge _remote/lock_judge_20261022.py."
        " Order: dual dumps, J1, dual trainings, control dumps, J2, control trainings (dumps first so they take a freed slot first).")
judge = "_remote/lock_judge_20261022.py"
lines = [head] + dump_lines[0] + [f"{J1}|{judge}|--stage main --out outputs/runs/{J1}/lock_main.json|lock judge main (CPU)|{','.join(deps1)}"]
lines += train_lines[0] + dump_lines[1]
lines += [f"{J2}|{judge}|--stage full --out outputs/runs/{J2}/lock_full.json|lock judge full (CPU)|{','.join([J1] + deps2)}"]
lines += train_lines[1]
open(sys.argv[1], "w").write("\n".join(lines) + "\n")
runs["seeds"] = SEEDS; runs["judges"] = {"main": J1, "full": J2}
json.dump(runs, open(sys.argv[2], "w"), indent=1)
print(len(train_lines[0]) + len(train_lines[1]), "trainings,", len(deps1) + len(deps2), "dumps, last dump id", P + str(nxt - 1))
