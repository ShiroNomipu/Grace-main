"""B1 job list (2026-10-22; card runs/锁定批_20261022/B1_GRACE修复重跑_卡_2026-10-22.md): GRACE (audio injected into
the LLM residual stream) retrained with the dropout-mask fix (--mdrop_consistent), 15 past turns like the lock batch,
audio on both datasets, 5 seeds, last epoch. Writes the queue file and b1_runs.json (the only map from seed to run id).
Usage (repo root): python <this> <jobs_out> <runs_json_out>"""
import json, sys
SEEDS = [123, 42, 3047, 7, 2026]
P = "R20261022-"
ARGS = {"iemocap": "--dataset iemocap --n_prev_turns 1 --n_blocks 2 --no_frame_attn --modality_dropout 0.3 --mdrop_consistent "
                   "--adapter_lr 5e-5 --adapter_wd 0.05 --cosine --epochs 3 --seed {s} --fast_eval --eval_last --ctx 16",
        "meld": "--dataset meld --meld_audio --n_prev_turns 1 --n_blocks 2 --no_frame_attn --modality_dropout 0.3 --mdrop_consistent "
                "--adapter_lr 8e-5 --adapter_wd 0.05 --cosine --focal_loss --focal_gamma 0.5 --epochs 3 --seed {s} --fast_eval --eval_last --ctx 16"}
TAG = {"iemocap": "pilot3_dial1t_2blk_iemocap_nofa_mdrop30c_alr5e-05_cos_s{s}_ctx16",
       "meld": "pilot3_dial1t_2blk_meld_nofa_mdrop30c_alr8e-05_cos_focal0.5_s{s}_ctx16_maudio"}
DUMP = {"iemocap": "--dataset iemocap", "meld": "--dataset meld --meld_audio"}
runs, train, dumps = {}, [], []
nt, nd = 301, 311
for ds in ("meld", "iemocap"):   # longer MELD runs first
    runs[ds] = {"train": [], "tag": [], "dump": {"dev": [], "test": []}}
    for s in SEEDS:
        t = P + str(nt); nt += 1; tag = TAG[ds].format(s=s)
        train.append(f"{t}|run_pilot3_dialogue_visual.py|{ARGS[ds].format(s=s)}|B1 grace fixed {ds} s{s}|")
        runs[ds]["train"].append(t); runs[ds]["tag"].append(tag)
        for sp in ("dev", "test"):
            d = P + str(nd); nd += 1
            dumps.append(f"{d}|eval_dump_preds.py|{DUMP[ds]} --split {sp} --n_blocks 2 --n_prev_turns 1 --no_frame_attn --fast_eval --ctx 16 "
                         f"--conditions clean drop --checkpoint outputs/runs/{t}/{tag}_last --out_dir outputs/runs/{d}/eval|B1 dump {ds} {sp} s{s}|{t}")
            runs[ds]["dump"][sp].append(d)
assert nt <= 311 and nd <= 340
J = P + "340"
head = ("# B1 (2026-10-22, user approved B1): GRACE with the dropout-mask fix, ctx 16, audio, 5 seeds x 2 datasets; card "
        "runs/锁定批_20261022/B1_GRACE修复重跑_卡_2026-10-22.md; generated by b1_jobs_gen_20261022.py; run_pilot3_dialogue_visual.py "
        "aaa8eab9, eval_dump_preds.py aed3ba0b; judge _remote/b1_grace_judge_20261022.py after the lock batch judge J2 (R20261022-211).")
judge = f"{J}|_remote/b1_grace_judge_20261022.py|--out outputs/runs/{J}/b1_grace.json|B1 judge (CPU)|{','.join(['R20261022-211'] + [l.split('|')[0] for l in dumps])}"
open(sys.argv[1], "w").write("\n".join([head] + dumps + [judge] + train) + "\n")
runs["seeds"] = SEEDS; runs["judge"] = J
json.dump(runs, open(sys.argv[2], "w"), indent=1)
print(len(train), "trainings,", len(dumps), "dumps")
